// Builds src/appHtml.js from web/Homebz.html (the original design, kept untouched)
// by inlining the fonts for offline use and adding the native shell CSS + bridge.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');

let html = read('web/Homebz.html');
const fonts = read('web/fonts.css');
const nativeCss = read('web/native.css');
const bridge = read('web/bridge.js');

const fontLink = /<link[^>]+fonts\.googleapis\.com[^>]*>/;
if (!fontLink.test(html)) throw new Error('Google Fonts <link> not found in web/Homebz.html');
html = html.replace(fontLink, () => `<style>${fonts}</style>`);
html = html.replace('</head>', () => `<style>${nativeCss}</style>\n</head>`);
const end = html.lastIndexOf('</body>');
if (end < 0) throw new Error('</body> not found in web/Homebz.html');
html = html.slice(0, end) + `<script>${bridge}</script>\n` + html.slice(end);

fs.writeFileSync(path.join(root, 'src/appHtml.js'), `// Generated by scripts/build-html.js — do not edit.\nexport default ${JSON.stringify(html)};\n`);
fs.writeFileSync(path.join(root, 'web/.preview.html'), html);
fs.writeFileSync(path.join(root, 'snack/app.html'), html);
// Home-screen web app version (same design, opens full screen from Safari).
const webMeta = '<meta name="apple-mobile-web-app-capable" content="yes"><meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-status-bar-style" content="default"><meta name="apple-mobile-web-app-title" content="Homebz"><link rel="apple-touch-icon" href="icon.png"><link rel="icon" href="icon.png">';
fs.mkdirSync(path.join(root, 'web-app'), { recursive: true });
fs.writeFileSync(path.join(root, 'web-app/index.html'), html.replace('</head>', () => webMeta + '\n</head>'));
fs.copyFileSync(path.join(root, 'assets/icon.png'), path.join(root, 'web-app/icon.png'));
console.log(`src/appHtml.js written (${Math.round(html.length / 1024)} KB)`);
